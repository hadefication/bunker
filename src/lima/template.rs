//! The Lima template: vz, no mounts, no host loopback, no DNS, no port forwards, no provisioning.
use crate::config::Config;
use crate::lima::image::ImageRef;

/// A double-quoted YAML scalar (JSON string syntax is valid YAML).
fn q(s: &str) -> String {
    serde_json::Value::String(s.to_string()).to_string()
}

/// The VM's Lima template. Containment settings are fixed; only size, image and SSH port vary.
pub fn render_lima_yaml(cfg: &Config, image: &ImageRef, vm_name: &str) -> String {
    format!(
        r#"# Lima template for {vm_name}, generated by bunker. Edits are overwritten by bunker up.
vmType: vz
images:
  - location: {location}
    arch: aarch64
    digest: {digest}
cpus: {cpus}
memory: {memory}
disk: {disk}
mounts: []
ssh:
  localPort: {ssh}
  forwardAgent: false
containerd:
  system: false
  user: false
video:
  display: none
rosetta:
  enabled: false
propagateProxyEnv: false
hostResolver:
  enabled: false
dns: ["127.0.0.1"]
networkOpts:
  hostLoopback: false
portForwards:
- {{guestIP: "127.0.0.1", guestPortRange: [1, 65535], proto: any, ignore: true}}
- {{guestIP: "0.0.0.0", guestPortRange: [1, 65535], proto: any, ignore: true}}
- {{guestIP: "::", guestPortRange: [1, 65535], proto: any, ignore: true}}
"#,
        location = q(&image.path.to_string_lossy()),
        digest = q(&format!("sha256:{}", image.sha256)),
        cpus = cfg.vm.cpus,
        memory = q(&cfg.vm.memory),
        disk = q(&cfg.vm.disk),
        ssh = cfg.ports.ssh,
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lima_yaml_has_containment_settings() {
        let cfg = Config::parse(&crate::config::fixture_config()).unwrap();
        let img = ImageRef {
            path: "/Users/x/.bunker/images/u.img".into(),
            sha256: "ab".repeat(32),
        };
        let y = render_lima_yaml(&cfg, &img, "bunker-life-os");
        for line in [
            "vmType: vz",
            "  - location: \"/Users/x/.bunker/images/u.img\"",
            "    arch: aarch64",
            &format!("    digest: \"sha256:{}\"", "ab".repeat(32)),
            "cpus: 2",
            "memory: \"2GiB\"",
            "disk: \"20GiB\"",
            "mounts: []",
            "  localPort: 60100",
            "  forwardAgent: false",
            "  system: false",
            "  user: false",
            "  display: none",
            "rosetta:\n  enabled: false",
            "propagateProxyEnv: false",
            "hostResolver:\n  enabled: false",
            "dns: [\"127.0.0.1\"]",
            "networkOpts:\n  hostLoopback: false",
            "- {guestIP: \"127.0.0.1\", guestPortRange: [1, 65535], proto: any, ignore: true}",
            "- {guestIP: \"0.0.0.0\", guestPortRange: [1, 65535], proto: any, ignore: true}",
            "- {guestIP: \"::\", guestPortRange: [1, 65535], proto: any, ignore: true}",
        ] {
            assert!(y.contains(line), "missing {line:?} in\n{y}");
        }
        assert!(
            !y.contains("template://") && !y.contains("provision:") && !y.contains("base:"),
            "{y}"
        );
    }
}
#[cfg(test)]
mod sys {
    use super::*;
    #[test]
    #[ignore]
    fn sys_lima_validates_template() {
        let cfg = Config::parse(&crate::config::fixture_config()).unwrap();
        let d = tempfile::tempdir().unwrap();
        let img = d.path().join("u.img");
        std::fs::write(&img, b"").unwrap();
        let y = render_lima_yaml(
            &cfg,
            &ImageRef {
                path: img,
                sha256: "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855".into(),
            },
            "bunker-t",
        );
        let f = d.path().join("bunker-t.yaml");
        std::fs::write(&f, y).unwrap();
        let out = std::process::Command::new("limactl")
            .arg("validate")
            .arg(&f)
            .output()
            .unwrap();
        assert!(
            out.status.success(),
            "{}",
            String::from_utf8_lossy(&out.stderr)
        );
    }
}
